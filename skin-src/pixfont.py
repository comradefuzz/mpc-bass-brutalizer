GLYPHS = {ch: [[c == "#" for c in row] for row in spec.split("|")] for ch, spec in _G.items()}
CELL = 6  # 5 px glyph + 1 px gap


def text_width(s, scale):
    return len(s) * CELL * scale - scale


def draw_text(plot, x, y, s, scale, colour):
    """plot(px, py, colour) is called for every lit pixel (scaled blocks)."""
    cx = x
    for ch in s.upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        for ry, row in enumerate(g):
            for rx, on in enumerate(row):
                if on:
                    for sy in range(scale):
                        for sx in range(scale):
                            plot(cx + rx * scale + sx, y + ry * scale + sy, colour)
        cx += CELL * scale
    return cx
